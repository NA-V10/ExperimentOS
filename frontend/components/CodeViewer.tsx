"use client";

import { useState } from "react";

export function CodeViewer({ code, source, language = "python" }: { code: string; source?: string | null; language?: string }) {
  const [copied, setCopied] = useState(false);
  const lines = code.replace(/\n$/, "").split("\n");
  return (
    <div className="overflow-hidden rounded-xl border border-line">
      <div className="flex items-center justify-between border-b border-line bg-surface-2 px-3 py-1.5 text-xs text-ink-2">
        <span className="font-mono">experiment.py · {language}</span>
        <span className="flex items-center gap-3">
          {source && (
            <span className={source === "nemotron" ? "font-medium text-accent" : ""}>
              {source === "nemotron" ? "Generated by Nemotron" : "Template generator"}
            </span>
          )}
          <button
            onClick={async () => {
              try { await navigator.clipboard.writeText(code); setCopied(true); setTimeout(() => setCopied(false), 1500); } catch { /* ignore */ }
            }}
            className="rounded px-1.5 py-0.5 hover:bg-surface"
          >
            {copied ? "Copied" : "Copy"}
          </button>
        </span>
      </div>
      <pre className="max-h-[28rem] overflow-auto bg-bg py-3 text-[12.5px] leading-[1.6]">
        <code>
          {lines.map((l, i) => (
            <div key={i} className="flex">
              <span className="w-10 shrink-0 select-none pr-3 text-right text-muted">{i + 1}</span>
              <span className="whitespace-pre pr-4">{l || " "}</span>
            </div>
          ))}
        </code>
      </pre>
    </div>
  );
}
